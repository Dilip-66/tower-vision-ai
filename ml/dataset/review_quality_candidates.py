PROJECT_ROOT = Path(__file__).resolve().parents[2]

REPORT_DIR = PROJECT_ROOT / "data" / "reports"
INTERIM_DIR = PROJECT_ROOT / "data" / "interim" / "quality_review"

QUALITY_ANALYSIS_PATH = (
    REPORT_DIR / "quality_analysis.csv"
)

CANDIDATE_PATH = (
    REPORT_DIR / "quality_rule_candidates.json"
)

OUTPUT_CSV = (
    REPORT_DIR
    / "quality_candidate_real_review.csv"
)

OUTPUT_JSON = (
    REPORT_DIR
    / "quality_candidate_real_review.json"
)

CONTACT_COLUMNS = 3

THUMBNAIL_WIDTH = 400
THUMBNAIL_HEIGHT = 290
LABEL_HEIGHT = 95

BACKGROUND = (245, 245, 245)
TEXT_COLOR = (20, 20, 20)
BORDER_COLOR = (170, 170, 170)


def load_quality_data() -> pd.DataFrame:
    """
    Load quality metrics calculated from the real dataset.
    """
    if not QUALITY_ANALYSIS_PATH.exists():
        raise FileNotFoundError(
            "quality_analysis.csv was not found.\n"
            "Run analyze_quality.py first."
        )

    dataframe = pd.read_csv(
        QUALITY_ANALYSIS_PATH
    )

    required_columns = {
        "frame_id",
        "source_group_id",
        "source_file_name",
        "source_relative_path",
        "frame_index",
        "sharpness_laplacian",
        "gradient_texture_mean",
        "mean_brightness",
        "dark_pixel_percentage",
        "bright_pixel_percentage",
    }

    missing = (
        required_columns
        - set(dataframe.columns)
    )

    if missing:
        raise ValueError(
            "quality_analysis.csv is missing "
            f"required columns: {sorted(missing)}"
        )

    return dataframe


def load_candidates() -> list[dict[str, Any]]:
    """
    Load the candidate rules generated by the optimizer.
    """
    if not CANDIDATE_PATH.exists():
        raise FileNotFoundError(
            "quality_rule_candidates.json was not found.\n"
            "Run optimize_quality_rules.py first."
        )

    with CANDIDATE_PATH.open(
        "r",
        encoding="utf-8",
    ) as file:
        payload = json.load(file)

    return payload.get(
        "candidates",
        [],
    )


def apply_candidate(
    dataframe: pd.DataFrame,
    candidate: dict[str, Any],
) -> pd.Series:
    """
    Apply one candidate rule to the real dataset.
    """
    metric_1 = candidate.get(
        "threshold_1_name"
    )

    threshold_1 = candidate.get(
        "threshold_1"
    )

    metric_2 = candidate.get(
        "threshold_2_name"
    )

    threshold_2 = candidate.get(
        "threshold_2"
    )

    problem = candidate.get(
        "problem"
    )

    operator = candidate.get(
        "operator"
    )

    if (
        metric_1 is None
        or threshold_1 is None
    ):
        return pd.Series(
            False,
            index=dataframe.index,
        )

    values_1 = pd.to_numeric(
        dataframe[metric_1],
        errors="coerce",
    )

    if problem == "blur":
        condition_1 = (
            values_1 < threshold_1
        )
    else:
        condition_1 = (
            values_1 > threshold_1
        )

    condition_1 = condition_1.fillna(
        False
    )

    if (
        metric_2 is None
        or threshold_2 is None
        or operator is None
    ):
        return condition_1

    values_2 = pd.to_numeric(
        dataframe[metric_2],
        errors="coerce",
    )

    if problem == "blur":
        condition_2 = (
            values_2 < threshold_2
        )
    else:
        condition_2 = (
            values_2 > threshold_2
        )

    condition_2 = condition_2.fillna(
        False
    )

    if operator == "AND":
        return (
            condition_1
            & condition_2
        )

    return (
        condition_1
        | condition_2
    )


def prepare_review_dataframe(
    dataframe: pd.DataFrame,
    candidates: list[dict[str, Any]],
) -> pd.DataFrame:
    """
    Apply every candidate rule and store the result.
    """
    result = dataframe.copy()

    result[
        "candidate_flag_blur"
    ] = False

    result[
        "candidate_flag_underexposure"
    ] = False

    result[
        "candidate_flag_overexposure"
    ] = False

    for candidate in candidates:
        problem = candidate.get(
            "problem"
        )

        flags = apply_candidate(
            result,
            candidate,
        )

        if problem == "blur":
            result[
                "candidate_flag_blur"
            ] = flags

        elif problem == "underexposure":
            result[
                "candidate_flag_underexposure"
            ] = flags

        elif problem == "overexposure":
            result[
                "candidate_flag_overexposure"
            ] = flags

    result[
        "candidate_flag_any"
    ] = (
        result[
            "candidate_flag_blur"
        ]
        | result[
            "candidate_flag_underexposure"
        ]
        | result[
            "candidate_flag_overexposure"
        ]
    )

    result[
        "candidate_flag_count"
    ] = (
        result[
            [
                "candidate_flag_blur",
                "candidate_flag_underexposure",
                "candidate_flag_overexposure",
            ]
        ]
        .sum(axis=1)
    )

    def build_reasons(
        row: pd.Series,
    ) -> str:
        reasons: list[str] = []

        if row[
            "candidate_flag_blur"
        ]:
            reasons.append(
                "blur"
            )

        if row[
            "candidate_flag_underexposure"
        ]:
            reasons.append(
                "underexposure"
            )

        if row[
            "candidate_flag_overexposure"
        ]:
            reasons.append(
                "overexposure"
            )

        if not reasons:
            return "none"

        return ",".join(
            reasons
        )

    result[
        "candidate_rejection_reasons"
    ] = result.apply(
        build_reasons,
        axis=1,
    )

    return result


def decode_frame(
    relative_path: str,
    frame_index: int,
) -> Image.Image:
    """
    Decode a real source frame into RGB.
    """
    path = (
        PROJECT_ROOT
        / relative_path
    )

    with Image.open(path) as image:
        image.seek(
            int(frame_index)
        )

        return image.convert(
            "RGB"
        ).copy()


def create_contact_sheet(
    dataframe: pd.DataFrame,
    filter_column: str,
    output_path: Path,
    title: str,
    maximum_images: int = 30,
) -> None:
    """
    Create a contact sheet for the frames flagged by a given
    candidate rule.

    The sheet is a visual review tool.
    """
    flagged = dataframe[
        dataframe[filter_column]
        == True
    ].copy()

    if flagged.empty:
        return

    flagged = flagged.head(
        maximum_images
    ).reset_index(
        drop=True
    )

    rows = math.ceil(
        len(flagged)
        / CONTACT_COLUMNS
    )

    cell_width = (
        THUMBNAIL_WIDTH
    )

    cell_height = (
        THUMBNAIL_HEIGHT
        + LABEL_HEIGHT
    )

    sheet = Image.new(
        "RGB",
        (
            cell_width
            * CONTACT_COLUMNS,
            cell_height
            * rows,
        ),
        BACKGROUND,
    )

    draw = ImageDraw.Draw(sheet)

    try:
        font = ImageFont.load_default()
    except Exception:
        font = None

    for index, (_, row) in enumerate(
        flagged.iterrows()
    ):
        column = (
            index
            % CONTACT_COLUMNS
        )

        row_number = (
            index
            // CONTACT_COLUMNS
        )

        x = (
            column
            * cell_width
        )

        y = (
            row_number
            * cell_height
        )

        try:
            image = decode_frame(
                relative_path=str(
                    row[
                        "source_relative_path"
                    ]
                ),
                frame_index=int(
                    row[
                        "frame_index"
                    ]
                ),
            )

            image.thumbnail(
                (
                    cell_width - 12,
                    THUMBNAIL_HEIGHT - 12,
                ),
                Image.Resampling.LANCZOS,
            )

            image_x = x + (
                cell_width
                - image.width
            ) // 2

            image_y = y + (
                THUMBNAIL_HEIGHT
                - image.height
            ) // 2

            sheet.paste(
                image,
                (
                    image_x,
                    image_y,
                ),
            )

            image.close()

            draw.rectangle(
                [
                    x + 3,
                    y + 3,
                    x + cell_width - 3,
                    y + THUMBNAIL_HEIGHT - 3,
                ],
                outline=BORDER_COLOR,
                width=2,
            )

            label = (
                f"{row['frame_id']}\n"
                f"Brightness: "
                f"{row['mean_brightness']:.2f} | "
                f"Sharpness: "
                f"{row['sharpness_laplacian']:.2f}\n"
                f"Dark %: "
                f"{row['dark_pixel_percentage']:.2f} | "
                f"Bright %: "
                f"{row['bright_pixel_percentage']:.2f}\n"
                f"Flag: "
                f"{row['candidate_rejection_reasons']}"
            )

            draw.text(
                (
                    x + 7,
                    y + THUMBNAIL_HEIGHT + 6,
                ),
                label,
                fill=TEXT_COLOR,
                font=font,
            )

        except Exception as exc:
            draw.text(
                (
                    x + 8,
                    y + 8,
                ),
                (
                    "Unable to decode\n"
                    f"{row['frame_id']}\n"
                    f"{type(exc).__name__}"
                ),
                fill=TEXT_COLOR,
                font=font,
            )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    sheet.save(
        output_path,
        quality=92,
    )

    sheet.close()


def calculate_summary(
    dataframe: pd.DataFrame,
) -> dict[str, Any]:
    """
    Build review statistics.
    """
    total = len(
        dataframe
    )

    summary: dict[str, Any] = {
        "real_frames": total,
        "candidate_rules": {},
    }

    rule_columns = {
        "blur": "candidate_flag_blur",
        "underexposure": (
            "candidate_flag_underexposure"
        ),
        "overexposure": (
            "candidate_flag_overexposure"
        ),
        "any": "candidate_flag_any",
        "multiple_issues": None,
    }

    for problem, column in rule_columns.items():
        if column is None:
            continue

        flagged = int(
            dataframe[column].sum()
        )

        summary[
            "candidate_rules"
        ][problem] = {
            "flagged": flagged,
            "total": total,
            "flag_rate": (
                flagged / total
                if total
                else 0.0
            ),
        }

    multiple = int(
        (
            dataframe[
                "candidate_flag_count"
            ]
            >= 2
        )
        .sum()
    )

    summary[
        "candidate_rules"
    ]["multiple_issues"] = {
        "flagged": multiple,
        "total": total,
        "flag_rate": (
            multiple / total
            if total
            else 0.0
        ),
    }

    return summary


def save_outputs(
    dataframe: pd.DataFrame,
    summary: dict[str, Any],
) -> None:
    """
    Save CSV and JSON review outputs.
    """
    REPORT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    INTERIM_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    dataframe.to_csv(
        OUTPUT_CSV,
        index=False,
        encoding="utf-8",
    )

    payload = {
        "summary": summary,
        "note": (
            "These flags are candidate quality-rule outputs "
            "for visual review. They are not production "
            "quality decisions."
        ),
    }

    with OUTPUT_JSON.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            payload,
            file,
            indent=2,
        )

    create_contact_sheet(
        dataframe=dataframe,
        filter_column="candidate_flag_blur",
        output_path=(
            INTERIM_DIR
            / "blur_flags.jpg"
        ),
        title="Blur Candidate Review",
    )

    create_contact_sheet(
        dataframe=dataframe,
        filter_column=(
            "candidate_flag_underexposure"
        ),
        output_path=(
            INTERIM_DIR
            / "underexposure_flags.jpg"
        ),
        title="Underexposure Candidate Review",
    )

    create_contact_sheet(
        dataframe=dataframe,
        filter_column=(
            "candidate_flag_overexposure"
        ),
        output_path=(
            INTERIM_DIR
            / "overexposure_flags.jpg"
        ),
        title="Overexposure Candidate Review",
    )

    multiple_dataframe = dataframe[
        dataframe[
            "candidate_flag_count"
        ]
        >= 2
    ].copy()

    create_contact_sheet(
        dataframe=multiple_dataframe,
        filter_column="candidate_flag_any",
        output_path=(
            INTERIM_DIR
            / "multi_issue_flags.jpg"
        ),
        title="Multiple Quality Issues",
    )

    print()
    print(
        f"CSV review report : {OUTPUT_CSV}"
    )

    print(
        f"JSON review report: {OUTPUT_JSON}"
    )

    print(
        "Blur review sheet  : "
        f"{INTERIM_DIR / 'blur_flags.jpg'}"
    )

    print(
        "Dark review sheet  : "
        f"{INTERIM_DIR / 'underexposure_flags.jpg'}"
    )

    print(
        "Bright review sheet: "
        f"{INTERIM_DIR / 'overexposure_flags.jpg'}"
    )

    print(
        "Multi-issue sheet  : "
        f"{INTERIM_DIR / 'multi_issue_flags.jpg'}"
    )


def print_summary(
    summary: dict[str, Any],
) -> None:
    """
    Print the candidate impact on the real dataset.
    """
    print()
    print("=" * 72)
    print(
        "REAL DATASET QUALITY CANDIDATE REVIEW"
    )
    print("=" * 72)

    print()
    print(
        f"Real frames analyzed: "
        f"{summary['real_frames']}"
    )

    print()

    for (
        problem,
        values,
    ) in summary[
        "candidate_rules"
    ].items():
        print(
            f"{problem:20} "
            f"{values['flagged']:3d} / "
            f"{values['total']:3d} "
            f"({values['flag_rate'] * 100:.2f}%)"
        )

    print()
    print("=" * 72)
    print(
        "VISUAL REVIEW REQUIRED"
    )
    print("=" * 72)
    print()


def main() -> None:
    """
    Main entry point.
    """
    print()
    print("=" * 72)
    print(
        "TOWERVISION AI - REAL DATASET QUALITY REVIEW"
    )
    print("=" * 72)
    print()

    quality = load_quality_data()

    candidates = load_candidates()

    if not candidates:
        raise ValueError(
            "No candidate quality rules were found."
        )

    print(
        f"Real frames: {len(quality)}"
    )

    print(
        f"Candidate rules: {len(candidates)}"
    )

    reviewed = prepare_review_dataframe(
        dataframe=quality,
        candidates=candidates,
    )

    summary = calculate_summary(
        reviewed
    )

    save_outputs(
        dataframe=reviewed,
        summary=summary,
    )

    print_summary(
        summary
    )


if __name__ == "__main__":
    main()